"""Reads data.json from rtd-travel-check and opens the PR with new answers.

Works in a throwaway clone, never in a developer's checkout.
"""
from __future__ import annotations

import json
import logging
import os
import subprocess
from pathlib import Path
from typing import List, Optional

from .config import TRAVEL_CHECK_BASE, TRAVEL_CHECK_REPO
from .countries import Countries

log = logging.getLogger(__name__)


def _run(args: List[str], cwd: Optional[Path] = None) -> str:
    res = subprocess.run(args, cwd=cwd, capture_output=True, text=True)
    if res.returncode != 0:
        # never echo the clone URL: it can contain a token
        raise RuntimeError(f"{args[0]} {args[1] if len(args) > 1 else ''} failed: {res.stderr.strip()[-500:]}")
    return res.stdout.strip()


def clone(dest: Path) -> Path:
    token = os.getenv("TRAVEL_CHECK_TOKEN", "").strip()
    auth = f"x-access-token:{token}@" if token else ""
    url = f"https://{auth}github.com/{TRAVEL_CHECK_REPO}.git"
    _run(["git", "clone", "--depth", "1", "--branch", TRAVEL_CHECK_BASE, url, str(dest)])
    return dest


def load_data(repo_dir: Path) -> List[dict]:
    with open(repo_dir / "data.json", encoding="utf-8") as f:
        return json.load(f)


def dump_data(data: List[dict], original_text: str) -> str:
    """Same layout as the existing file (2-space indent, keeps trailing-newline style)."""
    text = json.dumps(data, indent=2, ensure_ascii=False)
    return text + "\n" if original_text.endswith("\n") else text


def apply_answers(data: List[dict], entries: List[dict], countries: Countries) -> List[dict]:
    """Append one data.json row per answered country not already present."""
    covered = countries.covered_codes(data)
    out = list(data)
    for e in entries:
        if e["code"] in covered:
            continue
        a = e["answer"]
        out.append({
            "country": e["name"],
            "visaRequirement": a["visaRequirement"],
            "duration": a["duration"],
            "notes": a["notes"],
        })
        covered.add(e["code"])
    return out


def _md(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ").strip()


def pr_body(entries: List[dict]) -> str:
    rows = "\n".join(
        f"| {_md(e['name'])} | {_md(e['answer']['visaRequirement'])} | {_md(e['answer']['duration']) or '-'} "
        f"| {_md(e['answer']['notes']) or '-'} | {e['answer']['confidence']:.2f} |"
        for e in entries
    )
    quotes = "\n\n".join(
        f"**{e['name']}** (reply from `@{e['answer']['from_domain']}`, {e['answer']['received_at'][:10]}):\n"
        f"> {_md(e['answer']['evidence']) or '(no quote)'}"
        for e in entries
    )
    return f"""Embassy replies collected by [rtd-email-service](https://github.com/masonn99/rtd-email-service)'s automated pipeline.

| Country | Requirement | Duration | Notes | Confidence |
|---|---|---|---|---|
{rows}

### What each embassy wrote

{quotes}

Please check each quote matches the requirement before merging. If one is wrong, edit `data.json` on this branch or remove that row.

🤖 Generated by rtd-email-service
"""


def open_pr(repo_dir: Path, entries: List[dict], countries: Countries, today: str) -> str:
    path = repo_dir / "data.json"
    original = path.read_text(encoding="utf-8")
    data = apply_answers(json.loads(original), entries, countries)
    path.write_text(dump_data(data, original), encoding="utf-8")

    branch = f"embassy-replies/{today}"
    if _run(["git", "ls-remote", "--heads", "origin", branch], cwd=repo_dir):
        branch = f"{branch}-{os.getpid()}"
    _run(["git", "checkout", "-b", branch], cwd=repo_dir)
    _run(["git", "-c", "user.name=rtd-email-bot",
          "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
          "commit", "-am", f"Add embassy answers for {', '.join(e['name'] for e in entries)}"], cwd=repo_dir)
    _run(["git", "push", "origin", branch], cwd=repo_dir)

    names = ", ".join(e["name"] for e in entries[:4]) + (f" +{len(entries) - 4} more" if len(entries) > 4 else "")
    env_token = os.getenv("TRAVEL_CHECK_TOKEN", "").strip()
    env = {**os.environ, **({"GH_TOKEN": env_token} if env_token else {})}
    res = subprocess.run(
        ["gh", "pr", "create", "--repo", TRAVEL_CHECK_REPO, "--base", TRAVEL_CHECK_BASE, "--head", branch,
         "--title", f"Embassy answers: {names}", "--body", pr_body(entries)],
        cwd=repo_dir, capture_output=True, text=True, env=env,
    )
    if res.returncode != 0:
        raise RuntimeError(f"gh pr create failed: {res.stderr.strip()[-500:]}")
    return res.stdout.strip().splitlines()[-1]


def pr_state(url: str) -> Optional[str]:
    """OPEN / MERGED / CLOSED, or None if it can't be read."""
    env_token = os.getenv("TRAVEL_CHECK_TOKEN", "").strip()
    env = {**os.environ, **({"GH_TOKEN": env_token} if env_token else {})}
    res = subprocess.run(["gh", "pr", "view", url, "--json", "state", "-q", ".state"],
                         capture_output=True, text=True, env=env)
    if res.returncode != 0:
        return None
    return res.stdout.strip() or None
